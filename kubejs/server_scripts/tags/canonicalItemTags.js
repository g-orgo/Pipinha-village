ServerEvents.tags("item", (e) => {
  CANONICAL_TAG_CANDIDATES.forEach((tag) => {
    const members = [];
    e.get(tag).getObjectIds().forEach((id) => members.push(`${id}`));
    Object.keys(global.canonicalItems).forEach((dup) => {
      const canonical = global.canonicalItems[dup];
      if (members.includes(dup) && !members.includes(canonical)) e.add(tag, canonical);
    });
  });
});
