// Mercantil tree (society:mercantil), shared by every profession.
// XP: goods sold in a shipping bin (global.grantMercantilXp, called from
//   processValueOutput in globalShippingBinHandlers.js), gifts given to NPCs
//   and the first interaction with each NPC per day (global.grantMercantilNpcXp,
//   called from server_scripts/npcs/npcInteraction.js), and bounty papers turned
//   in at a Bounty Board (global.mercantilBountyXp, used by
//   server_scripts/playerEvents/mercantil.js), and spurs spent at NPC shops,
//   capped per day (global.grantMercantilPurchaseXp, called from
//   server_scripts/playerEvents/mercantilPurchases.js).
// Discounts: the Haggle I/II/III nodes grant mercantil_haggle_<tier>. Shop
//   trades relevant to a profession have discounted copies, generated by
//   sunlit_tools/mercantil_discounts.py, gated by derived stages:
//     mercantil_<group>_<tier>          cumulative, tier 1..3
//     mercantil_<group>_<tier>_<stage>  exact tier, for trades whose original
//                                       has stage_override <stage>
//   global.syncMercantilStages keeps the derived stages in line with the
//   player's haggle tier and professions (login and every 100 ticks).
// Original trades are never changed, so the Auto Trader keeps them.

global.MERCANTIL_TREE = "mercantil";
global.MERCANTIL_DISCOUNTS = [0.1, 0.15, 0.25];
// Trade groups and the professions that get their discount.
global.MERCANTIL_GROUPS = {
  farming: ["farmer"],
  husbandry: ["rancher"],
  breeding: ["rancher", "cook"],
  fishing: ["fisher"],
  wine: ["winemaker"],
  kitchen: ["cook"],
};
// stage_override values found on discounted trades (must match the generator).
global.MERCANTIL_OVERRIDE_STAGES = ["universal_methods_of_farming"];

global.mercantilTier = (player) => {
  for (let tier = global.MERCANTIL_DISCOUNTS.length; tier > 0; tier--) {
    if (player.stages.has(`mercantil_haggle_${tier}`)) return tier;
  }
  return 0;
};

global.syncMercantilStages = (player) => {
  let tier = global.mercantilTier(player);
  let professions = global.getProfessions(player);
  let maxTier = global.MERCANTIL_DISCOUNTS.length;
  Object.keys(global.MERCANTIL_GROUPS).forEach((group) => {
    let active = global.MERCANTIL_GROUPS[group].some((id) => professions.includes(id));
    let groupTier = active ? tier : 0;
    for (let t = 1; t <= maxTier; t++) {
      let stage = `mercantil_${group}_${t}`;
      let wanted = t <= groupTier;
      if (wanted && !player.stages.has(stage)) player.stages.add(stage);
      if (!wanted && player.stages.has(stage)) player.stages.remove(stage);
      global.MERCANTIL_OVERRIDE_STAGES.forEach((override) => {
        let exact = `${stage}_${override}`;
        let wantedExact = t === groupTier && player.stages.has(override);
        if (wantedExact && !player.stages.has(exact)) player.stages.add(exact);
        if (!wantedExact && player.stages.has(exact)) player.stages.remove(exact);
      });
    }
  });
};

// Sale value (in spurs) to Mercantil XP: square root curve, so early sales
// count and late game income does not race through the tree.
global.MERCANTIL_XP_CAP = 1500;
global.mercantilSaleXp = (value) =>
  Math.min(global.MERCANTIL_XP_CAP, Math.round(2 * Math.sqrt(Math.max(0, value))));

global.grantMercantilXp = (server, player, value) => {
  if (!player || player.isFake()) return;
  let xp = global.mercantilSaleXp(value);
  if (xp <= 0) return;
  // Mastery is left out: selling is not one of the five base crafts.
  global.giveExperience(server, player, global.MERCANTIL_TREE, xp, true);
};

// NPC relations: XP per gift by reaction (disliked/hated gifts give none) and
// for the first interaction with each NPC per day.
global.MERCANTIL_GIFT_XP = { loved: 40, liked: 25, neutral: 10, disliked: 0, hated: 0 };
global.MERCANTIL_GREETING_XP = 10;

global.grantMercantilNpcXp = (server, player, xp) => {
  if (!player || player.isFake() || !(xp > 0)) return;
  global.giveExperience(server, player, global.MERCANTIL_TREE, xp, true);
};

// Shop purchases: spurs spent at NPC shops (server_scripts/playerEvents/
// mercantilPurchases.js) follow the sale curve over the day's total, so
// splitting a purchase gives no extra XP, and the day is capped so buying to
// resell cannot farm the tree. The day is the in-game day of global.getDay.
global.MERCANTIL_PURCHASE_DAILY_CAP = 100;
global.mercantilPurchaseCurve = (spent) =>
  Math.min(global.MERCANTIL_PURCHASE_DAILY_CAP, Math.round(2 * Math.sqrt(Math.max(0, spent))));

global.grantMercantilPurchaseXp = (server, player, spent) => {
  if (!player || player.isFake() || !(spent > 0)) return 0;
  let data = player.persistentData;
  let day = global.getDay(player.level);
  let before = Number(data.getInt("mercantilPurchaseDay")) === day ? Number(data.getInt("mercantilPurchaseSpent")) : 0;
  let total = Math.min(before + spent, 1000000000);
  data.putInt("mercantilPurchaseDay", day);
  data.putInt("mercantilPurchaseSpent", total);
  let xp = global.mercantilPurchaseCurve(total) - global.mercantilPurchaseCurve(before);
  if (xp > 0) global.giveExperience(server, player, global.MERCANTIL_TREE, xp, true);
  return xp;
};

// Bounties: XP per paper turned in, by its rarity. Bountiful keeps the rarity in
// a JSON string under this NBT key and leaves it out when it is the default.
global.MERCANTIL_BOUNTY_INFO_KEY = "bountiful:bounty_info";
global.MERCANTIL_BOUNTY_XP = { COMMON: 40, UNCOMMON: 60, RARE: 80, EPIC: 100, LEGENDARY: 150 };

global.mercantilBountyXp = (stack) => {
  let table = global.MERCANTIL_BOUNTY_XP;
  try {
    return table[JSON.parse(stack.nbt.getString(global.MERCANTIL_BOUNTY_INFO_KEY)).rarity] || table.COMMON;
  } catch (err) {
    return table.COMMON;
  }
};
