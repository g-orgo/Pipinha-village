#!/usr/bin/env python3
"""Builds the list of finished dishes for the cook's first-dish bonus.

Usage: python3 -I sunlit_tools/cook_first_dishes.py <registry_audit dump.json>
Writes kubejs/server_scripts/playerEvents/cookFirstDishList.js.

A dish is an item of global.cooking with a sell value that is not:
  - removed from the pack (globalRemovedItems.js);
  - a storage block (crafted from 4 or more copies of one item);
  - an intermediate: used as an ingredient in a recipe (any type except the cutting
    board) whose result is another dish. Tags with more than TAG_LIMIT members are
    generic ("any meat") and do not turn their members into intermediates;
  - matched by NOT_FOOD (containers, doughs, raw parts);
  - a slice: cut on a board from another dish, or any *_slice portion served from a
    placed dish (cutting or serving a bought pie is not cooking);
  - an alcoholic drink (WINEMAKER, or poured from the Brewin' and Chewin' keg): those
    belong to the winemaker. Teas, coffees, juices and cocoa stay, they are cafe work.
Edibility is checked again in game (cookFirstDish.js), since jars do not list food values.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dish_prices import load_data, recipe_ingredients, recipe_result, tag_members  # noqa: E402

OUT = "kubejs/server_scripts/playerEvents/cookFirstDishList.js"
TAG_LIMIT = 6
SKIP_TYPES = {"farmersdelight:cutting", "kaleidoscope_cookery:chopping_board"}
# Platters and feast blocks assembled from finished dishes do not make those dishes intermediates.
PLATTER = re.compile(r"(_block|platter|medley)$")
NOT_FOOD = re.compile(
    r"(_crate|_bag|_cup|_tea_bag|dough|^.*:raw_|unripe_|pie_crust|:salt$|:butter$|_gel_block|honey_block)$"
    r"|(:raw_|unripe_|_dough|steamer_)"
)

NOT_FOOD_IDS = {
    "vintagedelight:ghost_charcoal", "youkaishomecoming:saucer", "youkaishomecoming:coffee_beans",
    "vintagedelight:vinegar_mason_jar", "society:tubasmoke_carton",
}
WINEMAKER = re.compile(r"^(kaleidoscope_tavern|vinery|nethervinery|longwings):|_wine$|:mead$|beer|sake_bottle")


def option_ids(part, tags):
    options = part if isinstance(part, list) else [part]
    ids = []
    for option in options:
        if not isinstance(option, dict):
            continue
        if "item" in option:
            ids.append(option["item"])
        elif "tag" in option:
            members = tag_members(option["tag"], tags)
            if len(members) <= TAG_LIMIT:
                ids += members
    return ids


def main():
    dump = json.load(open(sys.argv[1]))
    trades = dump["trades"]
    removed = open("kubejs/startup_scripts/globalRemovedItems.js").read()
    candidates = {}
    for entry in dump["lists"]["cooking"]:
        item = entry["item"]
        value = trades.get(item, {}).get("v") or 0
        if (value > 0 and f'"{item}"' not in removed and not NOT_FOOD.search(item)
                and item not in NOT_FOOD_IDS and not WINEMAKER.search(item)):
            candidates[item] = round(value)

    recipes, tags = load_data()
    storage, intermediate, alcohol, slices = set(), {}, set(), set()
    for recipe in recipes:
        kind = str(recipe.get("type"))
        result, count = recipe_result(recipe)
        listed = recipe.get("result")
        if not result and isinstance(listed, list) and listed and isinstance(listed[0], dict):
            result, count = listed[0].get("item"), listed[0].get("count", 1)  # cutting boards
        parts = recipe_ingredients(recipe)
        if kind == "brewinandchewin:keg_pouring" and result and result.startswith("brewinandchewin:"):
            alcohol.add(result)
        if not result or not parts:
            continue
        sets = [tuple(sorted(option_ids(p, tags))) for p in parts if p is not None]
        if len(sets) >= 4 and len(set(sets)) == 1 and count == 1:
            storage.add(result)
            continue
        if len(sets) == 1 and count >= 4:
            continue  # unpacking a storage block
        if kind in SKIP_TYPES and result in candidates:
            if any(item in candidates for ids in sets for item in ids):
                slices.add(result)
            continue
        if result not in candidates or PLATTER.search(result):
            continue
        for ids in sets:
            for item in ids:
                if item != result and item in candidates:
                    intermediate.setdefault(item, result)

    slices |= {i for i in candidates if i.endswith("_slice")}  # portions served from a placed dish
    dishes = sorted(i for i in candidates
                    if i not in storage and i not in intermediate and i not in alcohol and i not in slices)
    with open(OUT, "w") as handle:
        handle.write("// Generated by sunlit_tools/cook_first_dishes.py. Do not edit by hand.\n")
        handle.write("// Finished dishes that pay the cook's first-dish bonus (cookFirstDish.js).\n")
        handle.write("const COOK_FIRST_DISH_IDS = [\n")
        for item in dishes:
            handle.write(f'  "{item}",\n')
        handle.write("];\n")
    print(f"candidates {len(candidates)}, storage {len(storage & set(candidates))}, "
          f"intermediate {len(intermediate)}, keg drinks {len(alcohol)}, slices {len(slices)}, dishes {len(dishes)}")
    if "-v" in sys.argv:
        print("intermediate:", " ".join(sorted(intermediate)))
        print("slices:", " ".join(sorted(slices)))


if __name__ == "__main__":
    main()
